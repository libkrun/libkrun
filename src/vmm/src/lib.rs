    pub fn retain_layered_export(
        &mut self,
        service: retained_fds::RetainedFiles,
    ) -> std::io::Result<()> {
        self.layered_exports
            .retain(|service| !service.is_finished());
        // One idle service per live branch generation; each is a sleeping
        // thread with a small stack and no CPU cost, so this bound only guards
        // against a runaway caller rather than sizing a realistic fan-out.
        if self.layered_exports.len() >= 1024 {
            return Err(std::io::Error::other(
                "more than 1024 live branch generations retained for handoff; delete branches whose generation nothing else will branch from",
            ));
        }
        self.layered_exports.push(service);
        Ok(())
    }
    /// Whether guest RAM is a layered generation (a fork clone, or a source
    /// adopted as one). Capturing such RAM never rebases device windows, so a
    /// deferred save keeps a packed image's DAX file mappings intact.
    pub fn has_layered_ram(&self) -> bool {
        #[cfg(target_os = "linux")]
        {
            self.layered_ram.is_some()
        }
        #[cfg(not(target_os = "linux"))]
        {
            false
        }
    }

    #[cfg(target_os = "linux")]
    fn capture_layered_ram(&mut self) -> Result<Option<layered_restore::Generation>> {
        self.ensure_ram_mapping_valid()?;
        let Some(current) = &self.layered_ram else {
            return Ok(None);
        };
        let (next, copied) = current
            .capture_quiesced_excluding(&self.guest_memory, &self.layered_device_regions)
            .map_err(|error| Error::Snapshot(format!("capture modified RAM pages: {error}")))?;
        if let Err(error) =
            next.rebase_quiesced_excluding(&self.guest_memory, &self.layered_device_regions)
        {
            self.ram_remap_failure = Some(error.to_string());
            // Keep the complete captured backing even if installation stopped
            // partway through. Neither resume nor another capture may inspect
            // the partially replaced mappings as a valid generation.
            self.layered_ram = Some(next);
            return Err(Error::Snapshot(format!(
                "install captured RAM generation: {error}; VM remains stopped"
            )));
        }
        log::debug!("captured layered RAM generation: {copied} private bytes copied");
        self.layered_ram = Some(next.clone());
        Ok(Some(next))
    }
    /// Make a memfd-backed source a layered instance in place: seal its RAM
    /// files as the base generation and remap it privately over them. Nothing
    /// is copied; from here on a capture copies only the pages the source has
    /// written since the previous one, and a clone restored from such a
    /// generation stays a copy-on-write view even when it is branchable
    /// itself. The VM must be paused with its devices quiesced. Gated like
    /// `replay_fs_dax_maps`: only builds with the live-fork path remap RAM.
    #[cfg(all(target_os = "linux", fork_continue_supported, feature = "blk"))]
    fn adopt_layered_ram(&mut self) -> Result<()> {
        self.ensure_ram_mapping_valid()?;
        if self.layered_ram.is_some() {
            return Ok(());
        }
        let rebase = snapshot::rebase_guest_memory_private(&self.guest_memory);
        // The rebase replaced every file-backed host mapping, including the
        // virtio-fs DAX windows the guest still has page-table entries for.
        // That holds when it fails after the remap too (the kernel refuses the
        // write seal while it holds pages by reference): without the replay
        // the source resumes reading zeros for every file it had mapped, and
        // every exec into it fails with ENOEXEC.
        self.mmio_device_manager.replay_fs_dax_maps();
        rebase.map_err(|error| Error::Snapshot(format!("seal guest RAM generation: {error}")))?;
        let base = layered_restore::Generation::from_sealed_memory(&self.guest_memory)
            .map_err(|error| Error::Snapshot(format!("adopt guest RAM generation: {error}")))?;
        self.layered_ram = Some(base);
        Ok(())
    }
    #[cfg(snapshot_supported)]
    fn validate_restore_cpus(&self, checkpoint: &VmCheckpoint) -> Result<()> {
        if checkpoint.memory_growth != self.snapshot_memory_growth() {
            return Err(Error::VcpuSnapshot(
                "checkpoint boot RAM topology differs; restore into a new machine".into(),
            ));
        }
        #[cfg(all(
            any(target_os = "linux", target_os = "macos"),
            any(target_arch = "x86_64", target_arch = "aarch64"),
            not(feature = "tee")
        ))]
        if let Some(device) = &self.prototype_memory {
            let states: Vec<_> = checkpoint
                .devices
                .devices
                .iter()
                .filter_map(|s| {
                    if let devices::virtio::persist::DeviceSnapshot::Memory(s) = s {
                        Some(s)
                    } else {
                        None
                    }
                })
                .collect();
            if states.len() != 1 {
                return Err(Error::VcpuSnapshot(
                    "checkpoint RAM device missing or duplicated".into(),
                ));
            }
            let state = states[0];
            state.validate().map_err(Error::VcpuSnapshot)?;
            state
                .memory
                .validate_backing(&self.guest_memory)
                .map_err(Error::VcpuSnapshot)?;
            let device = device
                .lock()
                .map_err(|_| Error::VcpuSnapshot("RAM device poisoned".into()))?;
            if devices::virtio::VirtioDevice::is_activated(&*device)
                && device.save_state() != *state
            {
                return Err(Error::VcpuSnapshot(
                    "live RAM device state differs; restore into a new machine".into(),
                ));
            }
        }
        if checkpoint.vcpu_states.len() != self.vcpus_handles.len()
            || checkpoint.cpu_growth != self.snapshot_cpu_growth()
        {
            return Err(Error::VcpuSnapshot(
                "checkpoint CPU count or growth topology differs from this VM; restore into a machine configured for that checkpoint".into(),
            ));
        }
        // Restore installs the CPUID recorded in the checkpoint, so a guest
        // booted on a host with more features must not land on one without.
        #[cfg(all(target_os = "linux", target_arch = "x86_64"))]
        for state in &checkpoint.vcpu_states {
            state
                .check_host_support(self.vm.supported_cpuid())
                .map_err(Error::VcpuSnapshot)?;
        }
        #[cfg(all(target_os = "linux", target_arch = "x86_64", not(feature = "tee")))]
        self.cpu_growth_progress
            .check()
            .map_err(Error::VcpuSnapshot)?;
        Ok(())
    }

