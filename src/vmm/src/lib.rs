/// A full VM checkpoint, minus the guest-memory image (captured/streamed
/// separately because it is large). Combines the VM-level KVM state, per-vCPU
/// register state, and virtio device state. Produced by [`Vmm::checkpoint`] and
/// consumed by [`Vmm::restore`].
#[cfg(snapshot_supported)]
pub struct VmCheckpoint {
    /// VM-level KVM state (PIT, clock, PIC/IOAPIC).
    pub vm_state: vstate::VmState,
    /// Per-vCPU register state, in vCPU-index order.
    pub vcpu_states: Vec<vstate::VcpuState>,
    /// Virtio device runtime state (queues, negotiated features, etc.).
    pub devices: devices::virtio::persist::VmDevicesState,
    /// Userspace interrupt-controller registers. `None` on hypervisors whose
    /// IRQ chip is in-kernel and already inside `vm_state` (KVM) or captured
    /// separately (HVF GIC distributor). On WHP the IOAPIC is a software device
    /// in this process; without this section a restored clone boots with an
    /// all-masked redirection table and device IRQs (e.g. vsock) never arrive.
    pub ioapic: Option<Vec<u8>>,
    /// Guest discovery/CPUID policy for CPUs added after boot.
    pub cpu_growth: Option<cpu_growth::CpuGrowthTopology>,
    pub memory_growth: Option<memory_topology::MemoryGrowthTopology>,
}

/// Leads a checkpoint written by the macOS backend. Its VM and vCPU sections
/// are HVF-shaped, so another backend must translate them rather than parse
/// them. A blob without the tag is native to the backend reading it. Read as
/// a little-endian length the tag is over 1 GiB, which no untagged blob's
/// leading VM-state section can be.
#[cfg(snapshot_supported)]
const HVF_CHECKPOINT_TAG: &[u8; 8] = b"SMVCHVF1";
#[cfg(snapshot_supported)]
const KVM_ARM_CHECKPOINT_TAG: &[u8; 8] = b"SMVCKVM1";

/// A checkpoint blob split into its sections, before a hypervisor backend
/// interprets the VM and vCPU sections.
#[cfg(snapshot_supported)]
pub(crate) struct CheckpointSections<'a> {
    pub(crate) vm: &'a [u8],
    pub(crate) vcpus: Vec<&'a [u8]>,
    pub(crate) devices: devices::virtio::persist::VmDevicesState,
    pub(crate) ioapic: Option<Vec<u8>>,
    pub(crate) cpu_growth: Option<cpu_growth::CpuGrowthTopology>,
    pub(crate) memory_growth: Option<memory_topology::MemoryGrowthTopology>,
}

#[cfg(snapshot_supported)]
impl VmCheckpoint {
    /// Serialize the checkpoint (VM + vCPU + device state, *not* guest RAM —
    /// that is shared/streamed separately) into a single blob for cross-process
    /// fork or on-disk hibernate. Length-prefixed sections; no cross-version
    /// compatibility promised.
    pub fn serialize(&self) -> Vec<u8> {
        fn put(out: &mut Vec<u8>, b: &[u8]) {
            out.extend_from_slice(&(b.len() as u32).to_le_bytes());
            out.extend_from_slice(b);
        }
        let mut out = Vec::new();
        #[cfg(all(target_os = "macos", target_arch = "aarch64"))]
        out.extend_from_slice(HVF_CHECKPOINT_TAG);
        #[cfg(all(target_os = "linux", target_arch = "aarch64"))]
        out.extend_from_slice(KVM_ARM_CHECKPOINT_TAG);
        put(&mut out, &self.vm_state.serialize());
        out.extend_from_slice(&(self.vcpu_states.len() as u32).to_le_bytes());
        for v in &self.vcpu_states {
            put(&mut out, &v.serialize());
        }
        put(&mut out, &self.devices.to_bytes().unwrap_or_default());
        // Userspace IRQ-chip section; empty means "none" (in-kernel chip).
        put(&mut out, self.ioapic.as_deref().unwrap_or(&[]));
        if self.cpu_growth.is_some() || self.memory_growth.is_some() {
            put(
                &mut out,
                &self
                    .cpu_growth
                    .as_ref()
                    .map(|t| t.encode().to_vec())
                    .unwrap_or_default(),
            );
        }
        if let Some(topology) = &self.memory_growth {
            put(&mut out, &topology.encode());
        }
        out
    }

    /// Reconstruct from a blob produced by [`Self::serialize`], on this or (for
    /// a macOS arm64 checkpoint restored on Linux arm64) another backend.
    pub fn deserialize(bytes: &[u8]) -> std::result::Result<VmCheckpoint, String> {
        if let Some(body) = bytes.strip_prefix(KVM_ARM_CHECKPOINT_TAG) {
            #[cfg(all(target_os = "macos", target_arch = "aarch64"))]
            return kvm_import::import(Self::split_sections(body)?);
            #[cfg(all(target_os = "linux", target_arch = "aarch64"))]
            return Self::from_native_sections(Self::split_sections(body)?);
            #[cfg(not(all(
                any(target_os = "linux", target_os = "macos"),
                target_arch = "aarch64"
            )))]
            {
                let _ = body;
                return Err("This KVM checkpoint requires an arm64 host".into());
            }
        }
        let Some(body) = bytes.strip_prefix(HVF_CHECKPOINT_TAG) else {
            return Self::from_native_sections(Self::split_sections(bytes)?);
        };
        #[cfg(all(target_os = "macos", target_arch = "aarch64"))]
        return Self::from_native_sections(Self::split_sections(body)?);
        #[cfg(all(target_os = "linux", target_arch = "aarch64"))]
        return hvf_import::import(Self::split_sections(body)?);
        #[cfg(not(all(any(target_os = "macos", target_os = "linux"), target_arch = "aarch64")))]
        {
            let _ = body;
            Err(
                "this checkpoint was captured on an arm64 Mac and can only be restored \
                 on an arm64 Mac or arm64 Linux host"
                    .to_string(),
            )
        }
    }

    fn from_native_sections(
        sections: CheckpointSections<'_>,
    ) -> std::result::Result<VmCheckpoint, String> {
        let vm_state = vstate::VmState::deserialize(sections.vm)?;
        let vcpu_states = sections
            .vcpus
            .iter()
            .map(|bytes| vstate::VcpuState::deserialize(bytes))
            .collect::<std::result::Result<Vec<_>, _>>()?;
        Ok(VmCheckpoint {
            vm_state,
            vcpu_states,
            devices: sections.devices,
            ioapic: sections.ioapic,
            cpu_growth: sections.cpu_growth,
            memory_growth: sections.memory_growth,
        })
    }

    fn split_sections(bytes: &[u8]) -> std::result::Result<CheckpointSections<'_>, String> {
        fn take<'a>(b: &'a [u8], pos: &mut usize) -> std::result::Result<&'a [u8], String> {
            if *pos + 4 > b.len() {
                return Err("checkpoint truncated (length header)".to_string());
            }
            let len = u32::from_le_bytes(b[*pos..*pos + 4].try_into().unwrap()) as usize;
            *pos += 4;
            if *pos + len > b.len() {
                return Err("checkpoint truncated (section)".to_string());
            }
            let s = &b[*pos..*pos + len];
            *pos += len;
            Ok(s)
        }
        let mut pos = 0usize;
        let vm = take(bytes, &mut pos)?;
        if pos + 4 > bytes.len() {
            return Err("checkpoint truncated (vcpu count)".to_string());
        }
        let n = u32::from_le_bytes(bytes[pos..pos + 4].try_into().unwrap()) as usize;
        pos += 4;
        let mut vcpus = Vec::with_capacity(n.min(1024));
        for _ in 0..n {
            vcpus.push(take(bytes, &mut pos)?);
        }
        let devices = devices::virtio::persist::VmDevicesState::from_bytes(take(bytes, &mut pos)?)?;
        // Userspace IRQ-chip section: empty (or absent, for blobs written before
        // the section existed) means the chip is in-kernel and rides vm_state.
        let ioapic = if pos < bytes.len() {
            let b = take(bytes, &mut pos)?;
            (!b.is_empty()).then(|| b.to_vec())
        } else {
            None
        };
        let cpu_growth = if pos < bytes.len() {
            let section = take(bytes, &mut pos)?;
            if section.is_empty() {
                None
            } else {
                Some(cpu_growth::CpuGrowthTopology::decode(section, n)?)
            }
        } else {
            None
        };
        let memory_growth = if pos < bytes.len() {
            Some(memory_topology::MemoryGrowthTopology::decode(take(
                bytes, &mut pos,
            )?)?)
        } else {
            None
        };
        if pos != bytes.len() {
            return Err("unexpected trailing checkpoint state".into());
        }
        Ok(CheckpointSections {
            vm,
            vcpus,
            devices,
            ioapic,
            cpu_growth,
            memory_growth,
        })
    }
}

