// Only fork-continue publishes this marker, and that exists on linux-x86_64
// and macOS; deferring RAM to a stream (which aarch64 Linux now does) has no
// generation directory to commit.
#[cfg(all(feature = "blk", fork_continue_supported))]
fn publish_generation_commit_marker(path: &std::path::Path) -> io::Result<()> {
    if path.exists() {
        return Err(io::Error::new(
            io::ErrorKind::AlreadyExists,
            "fork generation commit marker already exists",
        ));
    }
    let partial = path.with_extension("partial");
    let mut published = false;
    let result = (|| {
        let mut file = std::fs::OpenOptions::new()
            .create_new(true)
            .write(true)
            .open(&partial)?;
        file.write_all(b"source-continues-v1\n")?;
        file.sync_all()?;
        std::fs::hard_link(&partial, path)?;
        published = true;
        let _ = std::fs::remove_file(&partial);
        let parent = path
            .parent()
            .ok_or_else(|| io::Error::new(io::ErrorKind::InvalidInput, "marker has no parent"))?;
        std::fs::File::open(parent)?.sync_all()
    })();
    if result.is_err() {
        if published {
            let _ = std::fs::remove_file(path);
        }
        let _ = std::fs::remove_file(partial);
    }
    result
}

